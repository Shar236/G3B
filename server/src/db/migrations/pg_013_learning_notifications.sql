CREATE TABLE learning_notifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES learning_assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  recipient varchar(190) NOT NULL,
  subject varchar(255) NOT NULL,
  body text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','failed')),
  attempts integer NOT NULL DEFAULT 0,
  last_error text,
  sent_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (assignment_id,student_id)
);
CREATE INDEX learning_notifications_pending_idx ON learning_notifications(status,created_at);
ALTER TABLE learning_notifications ENABLE ROW LEVEL SECURITY;
