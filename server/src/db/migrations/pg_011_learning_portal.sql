-- Private student assignments and resources. File bytes remain inside PostgreSQL
-- and are only streamed by authenticated, ownership-checked API handlers.
CREATE TABLE learning_assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL,
  description text NOT NULL DEFAULT '',
  instructions text NOT NULL DEFAULT '',
  category varchar(80) NOT NULL DEFAULT 'general',
  due_at timestamptz,
  status varchar(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX learning_assignments_status_due_idx ON learning_assignments(status, due_at);

CREATE TABLE learning_assignment_targets (
  assignment_id integer NOT NULL REFERENCES learning_assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  viewed_at timestamptz,
  PRIMARY KEY (assignment_id, student_id)
);
CREATE INDEX learning_targets_student_idx ON learning_assignment_targets(student_id, assigned_at DESC);

CREATE TABLE learning_assignment_files (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES learning_assignments(id) ON DELETE CASCADE,
  filename varchar(255) NOT NULL,
  mime_type varchar(100) NOT NULL,
  content bytea NOT NULL,
  size_bytes integer NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 10485760),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX learning_files_assignment_idx ON learning_assignment_files(assignment_id);

CREATE TABLE learning_submissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL,
  student_id integer NOT NULL,
  filename varchar(255) NOT NULL,
  mime_type varchar(100) NOT NULL,
  content bytea NOT NULL,
  size_bytes integer NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 10485760),
  submitted_at timestamptz NOT NULL DEFAULT now(),
  feedback text,
  marks varchar(40),
  reviewed_at timestamptz,
  UNIQUE (assignment_id, student_id),
  FOREIGN KEY (assignment_id, student_id)
    REFERENCES learning_assignment_targets(assignment_id, student_id) ON DELETE CASCADE
);
CREATE INDEX learning_submissions_student_idx ON learning_submissions(student_id, submitted_at DESC);

CREATE TABLE learning_announcements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL,
  body text NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX learning_announcements_status_idx ON learning_announcements(status, published_at DESC);

ALTER TABLE learning_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE learning_assignment_targets ENABLE ROW LEVEL SECURITY;
ALTER TABLE learning_assignment_files ENABLE ROW LEVEL SECURITY;
ALTER TABLE learning_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE learning_announcements ENABLE ROW LEVEL SECURITY;
