CREATE TABLE IF NOT EXISTS media_categories (
  id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  name        VARCHAR(100) NOT NULL,
  slug        VARCHAR(100) NOT NULL,
  media_type  ENUM('photo', 'video', 'all') NOT NULL DEFAULT 'all',
  sort_order  INT NOT NULL DEFAULT 0,
  is_active   TINYINT(1) NOT NULL DEFAULT 1,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_media_categories_slug (slug),
  KEY idx_media_categories_type (media_type, is_active)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS media_items (
  id                  INT UNSIGNED NOT NULL AUTO_INCREMENT,
  media_type          ENUM('photo', 'video') NOT NULL DEFAULT 'photo',
  title               VARCHAR(255) NOT NULL,
  slug                VARCHAR(190) NULL,
  description         TEXT NULL,
  caption             VARCHAR(500) NULL,
  alt_text            VARCHAR(255) NULL,
  category            VARCHAR(100) NOT NULL DEFAULT 'Events & Activities',
  storage_provider    VARCHAR(50) NOT NULL DEFAULT 'local',
  storage_key         VARCHAR(255) NULL,
  media_url           VARCHAR(500) NOT NULL,
  thumbnail_url       VARCHAR(500) NULL,
  external_video_url  VARCHAR(500) NULL,
  duration            VARCHAR(50) NULL,
  is_featured         TINYINT(1) NOT NULL DEFAULT 0,
  status              ENUM('draft', 'published', 'archived') NOT NULL DEFAULT 'published',
  sort_order          INT NOT NULL DEFAULT 0,
  created_by          INT UNSIGNED NULL,
  published_at        DATETIME NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_media_type_status (media_type, status),
  KEY idx_media_category (category),
  KEY idx_media_featured (is_featured),
  KEY idx_media_order (sort_order),
  CONSTRAINT fk_media_items_user FOREIGN KEY (created_by)
    REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

